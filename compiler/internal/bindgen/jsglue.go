// GenerateJSGlue generates the companion JavaScript file that implements the
// promise_env WASM imports for browser-targeted WebIDL bindings.
//
// The generated JS provides:
// - Reference table (refStore/refLoad/refRelease) for JS object handles
// - String marshalling (readString/writeString) via TextEncoder/TextDecoder
// - Per-import function implementations dispatching to actual DOM/browser APIs
// - WASM instantiation boilerplate
func GenerateJSGlue(modules []*Module) string {
	g := &jsGlueGenerator{}
	return g.generate(modules)
}

type jsGlueGenerator struct {
	buf strings.Builder
}

func (g *jsGlueGenerator) generate(modules []*Module) string {
	g.emitHeader()
	g.emitPALRuntime()
	g.emitRefTable()
	g.emitStringHelpers()
	g.emitImportObject(modules)
	g.emitInstantiation()
	return g.buf.String()
}

// GenerateBootstrapJS generates the bootstrap loader `promise build` writes
// beside every wasm32-web binary: the loader for a program with no WebIDL
// bindings. It is built from the same emitters as GenerateJSGlue, so the base
// PAL runtime the two loaders share — the promise_env.write/exit/
// monotonic_nanos imports, the exit unwind and the line buffering — is
// written once and cannot differ between them (#305).
//
// promise_env entries on the importObject passed to init() are added to the
// base imports and replace a base entry of the same name: that is how a page
// supplies a function a hand-declared `wasm_import` names. It is not a way to
// combine this loader with the bindgen glue, which exports no import object.
func GenerateBootstrapJS(wasmBase string) string {
	g := &jsGlueGenerator{}
	g.writef(`// Auto-generated bootstrap loader for %s — do not edit.
// A program with WebIDL bindings loads the glue from promise bind webidl
// instead of this file. promise_env entries on the importObject passed to
// init() are added to (and override) the base PAL imports below.

`, wasmBase)
	g.emitPALRuntime()
	g.write("// Base PAL runtime imports every wasm32-web binary needs.\n")
	g.write("const basePromiseEnv = {\n")
	g.emitBasePromiseEnvImports()
	g.write("};\n\n")
	g.writef(`export async function init(importObject = {}) {
  const response = await fetch("%s");
  const { instance } = await WebAssembly.instantiateStreaming(response, {
    ...importObject,
    promise_env: { ...basePromiseEnv, ...(importObject.promise_env || {}) },
  });
  wasm = instance;

`, wasmBase)
	g.emitRunInitialize()
	g.write(`
  return wasm.exports;
}
`)
	return g.buf.String()
}

func (g *jsGlueGenerator) writef(format string, args ...interface{}) {
	fmt.Fprintf(&g.buf, format, args...)
}

func (g *jsGlueGenerator) write(s string) {
	g.buf.WriteString(s)
}

func (g *jsGlueGenerator) emitHeader() {
	g.write(`// Auto-generated by promise bind webidl — do not edit.
// This file provides the JS glue for WASM browser bindings.

"use strict";

`)
}

func (g *jsGlueGenerator) emitRefTable() {
	g.write(`// --- Reference Table ---
// Maps integer handles to JS objects. Handle 0 is reserved (null).
const _refs = [undefined]; // slot 0 = null sentinel
const _freeList = [];

function _refStore(obj) {
  if (_freeList.length > 0) {
    const idx = _freeList.pop();
    _refs[idx] = obj;
    return idx;
  }
  _refs.push(obj);
  return _refs.length - 1;
}

function _refLoad(handle) {
  return _refs[handle];
}

function _refRelease(handle) {
  if (handle <= _pinnedMax) return;
  _refs[handle] = undefined;
  _freeList.push(handle);
}

// The ambient host references, seeded once at module load — before any import
// can run, so handle N is always _ambientRefs[N - 1] and the numbers mean the
// same thing in every host. Each entry is stored unconditionally: a DOM-less
// host leaves slot 2 holding undefined rather than shifting console down into
// it, which would otherwise make the handle numbers a property of the page.
//
// These references belong to the host, not to any wrapper, so releasing one is
// always a bug — and a silently aliasing one, since the freed slot would be
// handed to the next _refStore and a later _refLoad(2) would then read an
// unrelated object. _refRelease ignores them instead; wrap them with a
// resource's borrow() factory so no wrapper claims to own them (T1510).
const _ambientRefs = [
  globalThis,
  typeof document !== "undefined" ? document : undefined,
  typeof console !== "undefined" ? console : undefined,
];
for (const _ambient of _ambientRefs) _refStore(_ambient);
const _pinnedMax = _ambientRefs.length;

`)
}

func (g *jsGlueGenerator) emitStringHelpers() {
	g.write(`// --- String Marshalling ---
const _encoder = new TextEncoder();

function _readString(ptr, len) {
  const mem = new Uint8Array(wasm.exports.memory.buffer);
  return _decoder.decode(mem.subarray(ptr, ptr + len));
}

function _writeString(str) {
  const bytes = _encoder.encode(str);
  const ptr = wasm.exports.cabi_realloc(0, 0, 1, bytes.length);
  const mem = new Uint8Array(wasm.exports.memory.buffer);
  mem.set(bytes, ptr);
  return { ptr, len: bytes.length };
}

// A string result crosses as the canonical (ptr, len) pair, written through the
// trailing return pointer the caller supplies; the caller copies the bytes into
// its own string and frees the buffer. null/undefined write (0, 0), the empty
// string — a nullable DOMString result is a bare string at the boundary.
function _writeStringResult(retptr, str) {
  let ptr = 0, len = 0;
  if (str != null) ({ ptr, len } = _writeString(String(str)));
  // A fresh view: _writeString's allocation may have grown memory.
  const view = new DataView(wasm.exports.memory.buffer);
  view.setInt32(retptr, ptr, true);
  view.setInt32(retptr + 4, len, true);
}

`)
}

// emitPALRuntime writes the module-level base PAL runtime both loaders share
// (GenerateJSGlue and GenerateBootstrapJS): the instance binding, the decoder
// promise_env.write uses, the exit sentinel, and the line buffering.
//
// _ExitSignal is the typed sentinel exit() throws to unwind the synchronous
// WASM call stack — the only way to abort a WASM function from a JS import.
// Carrying the real exit code lets init() tell a normal main() return
// (pal_exit(0)) apart from a panic or an explicit non-zero exit(), instead of
// matching on a bare Error's .message string, which would also swallow any
// unrelated JS error that happened to carry the same text. It is exported so a
// caller can test `instanceof`: `.code` alone does not identify an exit, since
// a DOMException a host import throws carries a numeric `.code` too.
//
// The line buffering is what promise_env.write uses. console.log/console.error
// each add their own trailing newline, but Promise's print_line already appends
// Platform.line_separator before the write ever reaches the PAL (see
// definePrintStringBody in internal/codegen/io.go) — logging each write
// verbatim would double every line, and a write with no trailing newline
// would become its own console line, making it impossible to build one line
// out of several print() calls. Buffering per fd and flushing only on
// complete lines fixes both.
func (g *jsGlueGenerator) emitPALRuntime() {
	g.write(`let wasm;

const _decoder = new TextDecoder("utf-8");

export class _ExitSignal extends Error {
  constructor(code) {
    super("promise_env.exit");
    this.code = code;
  }
}

const _lineBuf = { 1: "", 2: "" };

function _flushLine(fd, line) {
  (fd === 2 ? console.error : console.log)(line);
}

function _writeChunk(fd, text) {
  const pending = _lineBuf[fd] + text;
  const lines = pending.split("\n");
  _lineBuf[fd] = lines.pop();
  for (const line of lines) _flushLine(fd, line);
}

function _flushRemainder() {
  for (const fd of [1, 2]) {
    if (_lineBuf[fd]) {
      _flushLine(fd, _lineBuf[fd]);
      _lineBuf[fd] = "";
    }
  }
}

`)
}

// emitBasePromiseEnvImports writes the promise_env.write/exit/monotonic_nanos
// entries every Promise wasm32-web binary imports unconditionally, regardless
// of which WebIDL bindings it also uses. Without these, WebAssembly.instantiate
// throws a LinkError before any binding code — or _initialize — ever runs, so
// the exit-unwind catch in emitRunInitialize has nothing to catch (T1506).
// Both loaders write these entries from here.
func (g *jsGlueGenerator) emitBasePromiseEnvImports() {
	g.write(`    write(fd, ptr, len) {
      // i64 args/returns are BigInts in default WebAssembly mode.
      const lenN = Number(len);
      if (lenN > 0) {
        const mem = new Uint8Array(wasm.exports.memory.buffer, Number(ptr), lenN);
        _writeChunk(Number(fd) === 2 ? 2 : 1, _decoder.decode(mem));
      }
      return BigInt(lenN);
    },
    exit(code) {
      throw new _ExitSignal(Number(code));
    },
    monotonic_nanos() {
      return BigInt(Math.round(performance.now() * 1e6));
    },
`)
}

func (g *jsGlueGenerator) emitImportObject(modules []*Module) {
	g.write("// --- Import Implementations ---\n")
	g.write("const importObject = {\n")

	for _, m := range modules {
		g.writef("  %s: {\n", m.ImportModule)

		if m.ImportModule == "promise_env" {
			g.emitBasePromiseEnvImports()
		}

		// Resource drop functions. Import name must match the WIT/component-model
		// canonical naming ("[resource-drop]<kebab-case>") that codegen.go's
		// emitResource emits on the .pr side — see toKebab, which both generators
		// must share rather than deriving this name independently (T1506).
		for _, res := range m.Resources {
			if res.Drop {
				importName := "[resource-drop]" + toKebab(res.Name)
				g.writef("    \"%s\"(handle) {\n", importName)
				g.write("      _refRelease(handle);\n")
				g.write("    },\n")
			}

			for _, method := range res.Methods {
				g.emitMethodImport(res.Name, method)
			}
		}

		// Free functions
		for _, f := range m.Functions {
			g.emitFreeFuncImport(f)
		}

		g.write("  },\n")
	}

	g.write("};\n\n")
}

func (g *jsGlueGenerator) emitMethodImport(resourceName string, f Func) {
	importName := f.ImportName
	if importName == "" {
		importName = resourceName + "." + f.Name
	}

	// Build JS parameter list
	jsParams := g.buildJSParams(f)

	g.writef("    \"%s\"(%s) {\n", importName, strings.Join(jsParams, ", "))

	switch f.Kind {
	case FuncConstructor:
		g.emitConstructorBody(resourceName, f, jsParams)
	case FuncStatic:
		g.emitStaticBody(resourceName, importName, f)
	default:
		g.emitMethodBody(importName, f)
	}

	g.write("    },\n")
}

func (g *jsGlueGenerator) emitFreeFuncImport(f Func) {
	importName := f.ImportName
	if importName == "" {
		importName = f.Name
	}
	jsParams := g.buildJSParams(f)

	g.writef("    \"%s\"(%s) {\n", importName, strings.Join(jsParams, ", "))
	// Free functions just call the global function
	g.writef("      return %s(%s);\n", idlCamelCase(f.Name), strings.Join(jsParams, ", "))
	g.write("    },\n")
}

func (g *jsGlueGenerator) buildJSParams(f Func) []string {
	var params []string

	// Methods get a handle parameter first
	if f.Kind == FuncMethod {
		params = append(params, "handle")
	}

	for _, p := range f.Params {
		name := jsParamName(p.Name)
		ref := p.Type
		// Unwrap option for the flat parameter
		if ref.Kind == OptionKind {
			ref = *ref.Elem
		}
		// String parameters are ptr+len pairs
		if isStringType(ref) {
			params = append(params, name+"_ptr", name+"_len")
		} else {
			params = append(params, name)
		}
	}

	// A string result comes back through a trailing return pointer — last, the
	// position codegen's declareExterns gives it (see _writeStringResult).
	if returnsString(f) {
		params = append(params, "retptr")
	}

	return params
}

// returnsString reports whether f's flat result is a string, a nullable one
// included: the extern declares a bare string for both (promiseExternType).
func returnsString(f Func) bool {
	if len(f.Results) == 0 {
		return false
	}
	ret := f.Results[0]
	if ret.Kind == OptionKind && ret.Elem != nil {
		ret = *ret.Elem
	}
	return isStringType(ret)
}

func (g *jsGlueGenerator) emitConstructorBody(resourceName string, f Func, jsParams []string) {
	// Convert parameters, call new Constructor(...), store ref
	args := g.buildJSCallArgs(f)
	g.writef("      const obj = new %s(%s);\n", resourceName, strings.Join(args, ", "))
	g.write("      return _refStore(obj);\n")
}

func (g *jsGlueGenerator) emitStaticBody(resourceName, importName string, f Func) {
	args := g.buildJSCallArgs(f)
	call := fmt.Sprintf("%s.%s(%s)", resourceName, importMember(importName), strings.Join(args, ", "))
	g.emitReturnConversion(f, call)
}

func (g *jsGlueGenerator) emitMethodBody(importName string, f Func) {
	args := g.buildJSCallArgs(f)
	member := importMember(importName)

	// Check if this is an attribute getter/setter.
	// Attribute import names have 3 parts: "Type.attrName.get/set"
	// Operation import names have 2 parts: "Type.methodName", or 3 when the
	// operation is the k-th of an overload set: "Type.methodName.k"
	parts := strings.Split(importName, ".")
	if len(parts) == 3 && parts[2] == "get" {
		call := fmt.Sprintf("_refLoad(handle).%s", member)
		g.emitReturnConversion(f, call)
		return
	}
	if len(parts) == 3 && parts[2] == "set" {
		g.writef("      _refLoad(handle).%s = %s;\n", member, strings.Join(args, ", "))
		return
	}

	call := fmt.Sprintf("_refLoad(handle).%s(%s)", member, strings.Join(args, ", "))
	g.emitReturnConversion(f, call)
}

// importMember returns the JS member an import invokes: the second dotted
// component of its import name — "Element.setAttribute", "Element.innerHTML.get"
// and "Element.setAttribute.2" all name a member of Element. The WebIDL front end
// writes the IDL identifier there verbatim, so this is the one place the glue
// reads a member name. It is never re-derived from the snake_case Promise name,
// which an overload ordinal (set_attribute_2) or an acronym (getURL → get_url)
// does not survive.
func importMember(importName string) string {
	parts := strings.Split(importName, ".")
	if len(parts) < 2 {
		return importName
	}
	return parts[1]
}

func (g *jsGlueGenerator) buildJSCallArgs(f Func) []string {
	var args []string
	for _, p := range f.Params {
		name := jsParamName(p.Name)
		ref := p.Type
		if ref.Kind == OptionKind {
			ref = *ref.Elem
		}
		if isStringType(ref) {
			args = append(args, fmt.Sprintf("_readString(%s_ptr, %s_len)", name, name))
		} else if isRefType(ref) {
			args = append(args, fmt.Sprintf("_refLoad(%s)", name))
		} else {
			args = append(args, name)
		}
	}
	return args
}

func (g *jsGlueGenerator) emitReturnConversion(f Func, call string) {
	if len(f.Results) == 0 {
		g.writef("      %s;\n", call)
		return
	}
	if returnsString(f) {
		// String return: (ptr, len) through the trailing retptr, nothing returned
		g.writef("      _writeStringResult(retptr, %s);\n", call)
		return
	}
	isNullable := f.Results[0].Kind == OptionKind
	ret := f.Results[0]
	// Unwrap option for the flat return type
	if ret.Kind == OptionKind && ret.Elem != nil {
		ret = *ret.Elem
	}
	if isRefType(ret) {
		if isNullable {
			g.writef("      const result = %s;\n", call)
			g.write("      if (result == null) return 0;\n")
			g.write("      return _refStore(result);\n")
		} else {
			g.writef("      return _refStore(%s);\n", call)
		}
	} else {
		g.writef("      return %s;\n", call)
	}
}

func (g *jsGlueGenerator) emitInstantiation() {
	g.write(`// --- WASM Instantiation ---
export async function init(wasmPath) {
  const response = await fetch(wasmPath);
  const { instance } = await WebAssembly.instantiateStreaming(response, importObject);
  wasm = instance;

`)
	g.emitRunInitialize()
	g.write(`
  return wasm.exports;
}

export { _refStore, _refLoad, _refRelease };
`)
}

// emitRunInitialize writes the body both loaders' init() run once the
// instance is bound to wasm: call _initialize and classify how it ended.
func (g *jsGlueGenerator) emitRunInitialize() {
	g.write(`  // Call WASM _initialize if exported. A normal main() return is signaled by
  // pal_exit(0), which lowers to the promise_env.exit import — the only way
  // to abort a synchronous WASM call from a JS import is to throw, so exit()
  // always throws to unwind the call stack. That's expected on success, not
  // a crash, so swallow exactly that case; a non-zero code (a panic, or an
  // explicit exit()) must still propagate so the caller learns the run
  // failed instead of getting exports back silently (T1506).
  if (wasm.exports._initialize) {
    try {
      wasm.exports._initialize();
    } catch (e) {
      if (!(e instanceof _ExitSignal) || e.code !== 0) {
        _flushRemainder();
        throw e;
      }
    }
  }
  _flushRemainder();
`)
}

// isStringType checks if a TypeRef maps to a string in the binding IR.
func isStringType(ref TypeRef) bool {
	return ref.Kind == BuiltinKind && ref.Builtin == "string"
}

// isRefType checks if a TypeRef maps to a JS object reference (handle).
//
// This intentionally returns true for *every* NamedKind, including JsValue. On the
// JS side a JsValue genuinely IS a ref-table handle (a JS value is stored/loaded via
// _refStore/_refLoad, identical to a resource), so the existing read/write glue is
// correct for it here. The Promise (WASM) side is where JsValue diverges from a
// resource — it marshals to/from the JsValue *enum* rather than an `i32 _handle`
// field; that asymmetry is handled in codegen.go (isJsValueRef and friends, T0723).
// Do NOT exclude JsValue here, or the JS-side conversion will break.
func isRefType(ref TypeRef) bool {
	if ref.Kind == NamedKind {
		return true
	}
	return false
}

// jsParamName converts a snake_case parameter name to a JS-safe identifier.
func jsParamName(name string) string {
	// Avoid JS reserved words
	switch name {
	case "default", "class", "function", "var", "let", "const", "this", "new", "delete", "in", "typeof":
		return name + "_"
	}
	return name
}

// idlCamelCase converts snake_case back to camelCase for JS method names.
// "get_element_by_id" → "getElementById"
func idlCamelCase(s string) string {
	parts := strings.Split(s, "_")
	if len(parts) <= 1 {
		return s
	}
	var b strings.Builder
	b.WriteString(parts[0])
	for _, part := range parts[1:] {
		if len(part) == 0 {
			continue
		}
		r, size := utf8.DecodeRuneInString(part)
		b.WriteRune(unicode.ToUpper(r))
		b.WriteString(part[size:])
	}
	return b.String()
}
