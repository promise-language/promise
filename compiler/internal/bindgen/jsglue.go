// GenerateJSGlue generates the companion JavaScript file that implements the
// promise_env WASM imports for browser-targeted WebIDL bindings.
//
// The generated JS provides:
// - Reference table (refStore/refLoad/refRelease) for JS object handles
// - String marshalling (readString/writeString) via TextEncoder/TextDecoder
// - Per-import function implementations dispatching to actual DOM/browser APIs
// - WASM instantiation boilerplate
func GenerateJSGlue(modules []*Module) string {
	g := &jsGlueGenerator{kinds: namedKinds(modules)}
	return g.generate(modules)
}

type jsGlueGenerator struct {
	buf strings.Builder
	// kinds classifies the names the modules define (namedKinds), the same
	// registry the Promise side lowers and lifts by.
	kinds kindRegistry
}

func (g *jsGlueGenerator) generate(modules []*Module) string {
	g.emitHeader()
	g.emitPALRuntime()
	g.emitRefTable()
	g.emitStringHelpers()
	g.emitOptionalResultHelper()
	if slices.ContainsFunc(modules, func(m *Module) bool { return m.HasJsValue }) {
		g.emitJsValueRuntime()
	}
	g.emitImportObject(modules)
	g.emitInstantiation()
	return g.buf.String()
}

// GenerateBootstrapJS generates the bootstrap loader `promise build` writes
// beside every wasm32-web binary: the loader for a program with no WebIDL
// bindings. It is built from the same emitters as GenerateJSGlue, so the base
// PAL runtime the two loaders share — the promise_env.write/exit/
// monotonic_nanos imports, the exit unwind and the line buffering — is
// written once and cannot differ between them (#305).
//
// Beyond the shared base, it carries the host side of modules/web — the
// hand-written, no-bindgen surface of
// docs/web-apps.md#it-must-be-usable-without-bindgen — over the same
// ref table the bindgen glue uses, so a handle means the same thing in both.
//
// promise_env entries on the importObject passed to init() are added to the
// base imports and replace a base entry of the same name: that is how a page
// supplies a function a hand-declared `wasm_import` names. It is not a way to
// combine this loader with the bindgen glue, which exports no import object.
func GenerateBootstrapJS(wasmBase string) string {
	g := &jsGlueGenerator{}
	g.writef(`// Auto-generated bootstrap loader for %s — do not edit.
// A program with WebIDL bindings loads the glue from promise bind webidl
// instead of this file. promise_env entries on the importObject passed to
// init() are added to (and override) the base PAL imports below.

`, wasmBase)
	g.emitPALRuntime()
	g.emitRefTable()
	g.emitStringHelpers()
	g.write("// Base PAL runtime imports every wasm32-web binary needs, and modules/web's.\n")
	g.write("const basePromiseEnv = {\n")
	g.emitBasePromiseEnvImports()
	g.emitWebModuleImports()
	g.write("};\n\n")
	g.writef(`export async function init(importObject = {}) {
  const response = await fetch("%[1]s");
  const { instance } = await WebAssembly.instantiateStreaming(response, {
    ...importObject,
    %[2]s: { ...basePromiseEnv, ...(importObject.%[2]s || {}) },
  });
  wasm = instance;

`, wasmBase, wasmweb.ImportModule)
	g.emitRunInitialize()
	g.write(`
  return wasm.exports;
}
`)
	return g.buf.String()
}

func (g *jsGlueGenerator) writef(format string, args ...interface{}) {
	fmt.Fprintf(&g.buf, format, args...)
}

func (g *jsGlueGenerator) write(s string) {
	g.buf.WriteString(s)
}

func (g *jsGlueGenerator) emitHeader() {
	g.write(`// Auto-generated by promise bind webidl — do not edit.
// This file provides the JS glue for WASM browser bindings.

"use strict";

`)
}

func (g *jsGlueGenerator) emitRefTable() {
	g.write(`// --- Reference Table ---
// Maps integer handles to JS objects. Handle 0 is reserved (null).
const _refs = [undefined]; // slot 0 = null sentinel
const _freeList = [];

function _refStore(obj) {
  if (_freeList.length > 0) {
    const idx = _freeList.pop();
    _refs[idx] = obj;
    return idx;
  }
  _refs.push(obj);
  return _refs.length - 1;
}

function _refLoad(handle) {
  return _refs[handle];
}

function _refRelease(handle) {
  if (handle <= _pinnedMax) return;
  _refs[handle] = undefined;
  _freeList.push(handle);
}

// The ambient host references, seeded once at module load — before any import
// can run, so handle N is always _ambientRefs[N - 1] and the numbers mean the
// same thing in every host. Each entry is stored unconditionally: a DOM-less
// host leaves slot 2 holding undefined rather than shifting console down into
// it, which would otherwise make the handle numbers a property of the page.
//
// These references belong to the host, not to any wrapper, so releasing one is
// always a bug — and a silently aliasing one, since the freed slot would be
// handed to the next _refStore and a later _refLoad(2) would then read an
// unrelated object. _refRelease ignores them instead; the generated roots
// (web.document) wrap them with a resource's borrow() factory so no wrapper
// claims to own them (T1510). This list is rendered from bindgen's
// ambientRefs, the same table the roots read their handles from.
const _ambientRefs = [
`)
	for _, a := range ambientRefs {
		g.writef("  typeof %s !== \"undefined\" ? %s : undefined,\n", a.global, a.global)
	}
	g.write(`];
for (const _ambient of _ambientRefs) _refStore(_ambient);
const _pinnedMax = _ambientRefs.length;

`)
}

func (g *jsGlueGenerator) emitStringHelpers() {
	g.write(`// --- String Marshalling ---
const _encoder = new TextEncoder();

function _readString(ptr, len) {
  const mem = new Uint8Array(wasm.exports.memory.buffer);
  return _decoder.decode(mem.subarray(ptr, ptr + len));
}

function _writeString(str) {
  const bytes = _encoder.encode(str);
  const ptr = wasm.exports.cabi_realloc(0, 0, 1, bytes.length);
  const mem = new Uint8Array(wasm.exports.memory.buffer);
  mem.set(bytes, ptr);
  return { ptr, len: bytes.length };
}

// A string result crosses as the canonical (ptr, len) pair, written through the
// trailing return pointer the caller supplies; the caller copies the bytes into
// its own string and frees the buffer. null/undefined write (0, 0), the empty
// string.
function _writeStringResult(retptr, str) {
  let ptr = 0, len = 0;
  if (str != null) ({ ptr, len } = _writeString(String(str)));
  // A fresh view: _writeString's allocation may have grown memory.
  const view = new DataView(wasm.exports.memory.buffer);
  view.setInt32(retptr, ptr, true);
  view.setInt32(retptr + 4, len, true);
}

`)
}

// emitOptionalResultHelper writes _writeOptionalResult, which every import whose
// result is a nullable built-in returns through (emitReturnConversion). Its
// offsets are rendered from wasmweb, the layout codegen reads the return area by
// (docs/wasm-bindings.md §"Helper Symbols and Their ABI").
func (g *jsGlueGenerator) emitOptionalResultHelper() {
	g.writef(`// A nullable built-in result crosses through the trailing return pointer: an
// i32 presence flag at offset %[1]d, then, when present, the value at offset %[2]d —
// a string as _writeStringResult writes it, anything else through the DataView
// setter its core type names. null and undefined are absent.
function _writeOptionalResult(retptr, v, setter) {
  const present = v != null;
  if (present) {
    if (setter === "string") _writeStringResult(retptr + %[2]d, v);
    else new DataView(wasm.exports.memory.buffer)[setter](retptr + %[2]d, v, true);
  }
  // A fresh view: _writeStringResult's allocation may have grown memory.
  new DataView(wasm.exports.memory.buffer).setInt32(retptr + %[1]d, present ? 1 : 0, true);
}

`, wasmweb.OptionalResultFlagOffset, wasmweb.OptionalResultValueOffset)
}

// optionalResultSetter names how _writeOptionalResult writes a present value of
// the built-in elem: "string" for a string, else the DataView setter of the core
// value it crosses as (flattenBuiltin). Each setter converts as the JS API does a
// value returned directly — ToInt32, ToBigInt64, or ToNumber then rounding — so a
// present value crosses exactly as a non-null result of its type would.
func optionalResultSetter(elem TypeRef) string {
	if isStringType(elem) {
		return "string"
	}
	switch flattenBuiltin(elem.Builtin)[0] {
	case FlatI64:
		return "setBigInt64"
	case FlatF32:
		return "setFloat32"
	case FlatF64:
		return "setFloat64"
	default:
		return "setInt32"
	}
}

// emitJsValueRuntime writes the glue's half of JsValue's crossing
// (docs/wasm-bindings.md §"JsValue the Dynamic Value Enum"; the Promise half is
// codegen.go's emitJsValueConversions). A builder import stores a value the
// program built in a temporary slot, and the import that receives it as an
// argument reads it with _refTake, which releases a temporary slot once read —
// before the host call, so a host that throws leaks nothing. Every other
// handle, an Object a JsValue holds among them, stays where it is.
// _jsValueTag is rendered from jsValueCases, the table _js_value_from_ref
// dispatches on, so a tag means the same variant on both sides.
func (g *jsGlueGenerator) emitJsValueRuntime() {
	g.write(`// --- JsValue ---
const _tempRefs = new Set();

function _refStoreTemp(value) {
  const handle = _refStore(value);
  _tempRefs.add(handle);
  return handle;
}

function _refTake(handle) {
  const value = _refLoad(handle);
  if (_tempRefs.delete(handle)) _refRelease(handle);
  return value;
}

// The JsValue variant a JS value lifts as, by its tag.
function _jsValueTag(v) {
`)
	fallback := 0
	for i, c := range jsValueCases {
		if c.jsTest == "" {
			fallback = i
			continue
		}
		g.writef("  if (%s) return %d;\n", c.jsTest, i)
	}
	g.writef("  return %d;\n}\n\n", fallback)
}

// emitJsValueImports writes the imports codegen.go's emitJsValueConversions
// declares, from the same jsValueCases: a builder per variant that holds no
// ref, js_value_tag, a getter per primitive, and js_value_release.
func (g *jsGlueGenerator) emitJsValueImports() {
	for _, c := range jsValueCases {
		if c.holdsRef {
			continue
		}
		g.writef("    %s(%s) {\n      return _refStoreTemp(%s);\n    },\n", jsValueBuilder(c), jsValueBuilderParams(c), c.jsStore)
	}
	g.writef("    %s(handle) {\n      return _jsValueTag(_refLoad(handle));\n    },\n", jsValueTagImport)
	for _, c := range jsValueCases {
		if c.payload == "" {
			continue
		}
		switch c.payload {
		case "string":
			// The canonical (ptr, len) pair, through the trailing return pointer.
			g.writef("    %s(handle, retptr) {\n      _writeStringResult(retptr, _refLoad(handle));\n    },\n", jsValueGetter(c))
		case "bool":
			g.writef("    %s(handle) {\n      return _refLoad(handle) ? 1 : 0;\n    },\n", jsValueGetter(c))
		default:
			g.writef("    %s(handle) {\n      return _refLoad(handle);\n    },\n", jsValueGetter(c))
		}
	}
	g.writef("    %s(handle) {\n      _refRelease(handle);\n    },\n", jsValueReleaseImport)
}

// emitPALRuntime writes the module-level base PAL runtime both loaders share
// (GenerateJSGlue and GenerateBootstrapJS): the instance binding, the decoder
// promise_env.write uses, the exit sentinel, and the line buffering.
//
// _ExitSignal is the typed sentinel exit() throws to unwind the synchronous
// WASM call stack — the only way to abort a WASM function from a JS import.
// Carrying the real exit code lets init() tell a normal main() return
// (pal_exit(0)) apart from a panic or an explicit non-zero exit(), instead of
// matching on a bare Error's .message string, which would also swallow any
// unrelated JS error that happened to carry the same text. It is exported so a
// caller can test `instanceof`: `.code` alone does not identify an exit, since
// a DOMException a host import throws carries a numeric `.code` too.
//
// The line buffering is what promise_env.write uses. console.log/console.error
// each add their own trailing newline, but Promise's print_line already appends
// Platform.line_separator before the write ever reaches the PAL (see
// definePrintStringBody in internal/codegen/io.go) — logging each write
// verbatim would double every line, and a write with no trailing newline
// would become its own console line, making it impossible to build one line
// out of several print() calls. Buffering per fd and flushing only on
// complete lines fixes both.
func (g *jsGlueGenerator) emitPALRuntime() {
	g.writef(`let wasm;

const _decoder = new TextDecoder("utf-8");

export class _ExitSignal extends Error {
  constructor(code) {
    super("%s.exit");
    this.code = code;
  }
}

const _lineBuf = { 1: "", 2: "" };

function _flushLine(fd, line) {
  (fd === 2 ? console.error : console.log)(line);
}

function _writeChunk(fd, text) {
  const pending = _lineBuf[fd] + text;
  const lines = pending.split("\n");
  _lineBuf[fd] = lines.pop();
  for (const line of lines) _flushLine(fd, line);
}

function _flushRemainder() {
  for (const fd of [1, 2]) {
    if (_lineBuf[fd]) {
      _flushLine(fd, _lineBuf[fd]);
      _lineBuf[fd] = "";
    }
  }
}

`, wasmweb.ImportModule)
	g.writef(`// Set by the exit import, which every exit passes through — a drain that
// ends the program, a panic, the debug allocator's abort. Once set, the
// loader makes no further call into the instance.
let _exited = false;

// _enter makes one host entry into the instance. The instance unwinds through
// the exit import, so a normal end is an _ExitSignal with code 0, which is
// swallowed; any other code, or any other error, propagates to whoever made
// the entry, so a failure is never silent.
function _enter(entry) {
  if (_exited) return;
  try {
    entry();
  } catch (e) {
    _flushRemainder();
    if (!(e instanceof _ExitSignal) || e.code !== 0) throw e;
  }
}

// schedule_pump (docs/web-apps.md#budget-and-continuation): the reactor asks
// the host to call %[1]s again. kind 0 = ASAP (a MessageChannel,
// free of setTimeout(0)'s ~4ms clamp), 1 = Timer (setTimeout(delayMs)),
// 2 = AnimationFrame (requestAnimationFrame). A drain may end the program, so
// a pump is a host entry like any other.
let _asapChannel;
const _asapQueue = [];

function _pump() {
  _enter(() => wasm.exports.%[1]s());
}

// _deliver hands one event to subscription id and pumps so its subscriber
// runs (docs/web-apps.md#delivery-js-enqueues-and-promise-code-consumes). The
// handle enqueue hands back — the rejected event, or the one the overflow
// policy displaced — is released; the null handle it returns otherwise is
// ignored by _refRelease.
function _deliver(id, obj) {
  if (_exited) return;
  _refRelease(wasm.exports.%[2]s(id, _refStore(obj)));
  _pump();
}

`, wasmweb.ExportPump, wasmweb.ExportEnqueue)
	g.write(`function _schedulePump(kind, delayMs) {
  if (kind === 1) {
    setTimeout(_pump, delayMs);
    return;
  }
  if (kind === 2) {
    requestAnimationFrame(_pump);
    return;
  }
  // In Node.js a port holds the process open while it is ref'd, and assigning
  // onmessage refs it. It is ref'd exactly while a continuation is pending: an
  // idle loader holds nothing open, so liveness comes only from real
  // registrations (docs/web-apps.md#the-liveness-rule), and a scheduled pump
  // still runs rather than the process exiting with work left. Browsers have no
  // such concept.
  if (!_asapChannel) {
    _asapChannel = new MessageChannel();
    _asapChannel.port1.onmessage = () => {
      const fn = _asapQueue.shift();
      if (_asapQueue.length === 0 && typeof _asapChannel.port1.unref === "function") {
        _asapChannel.port1.unref();
      }
      if (fn) fn();
    };
    if (typeof _asapChannel.port2.unref === "function") _asapChannel.port2.unref();
  }
  _asapQueue.push(_pump);
  if (typeof _asapChannel.port1.ref === "function") _asapChannel.port1.ref();
  _asapChannel.port2.postMessage(null);
}

`)
}

// emitBasePromiseEnvImports writes the promise_env.write/exit/monotonic_nanos
// and schedule_pump entries every Promise wasm32-web binary imports
// unconditionally, regardless of which WebIDL bindings it also uses —
// schedule_pump because every wasm32-web link exports the reactor's
// promise_web_pump, which calls it. Without these, WebAssembly.instantiate
// throws a LinkError before any binding code — or _initialize — ever runs, so
// the exit-unwind catch in emitRunInitialize has nothing to catch (T1506).
// Both loaders write these entries from here.
func (g *jsGlueGenerator) emitBasePromiseEnvImports() {
	g.write(`    write(fd, ptr, len) {
      // i64 args/returns are BigInts in default WebAssembly mode.
      const lenN = Number(len);
      if (lenN > 0) {
        const mem = new Uint8Array(wasm.exports.memory.buffer, Number(ptr), lenN);
        _writeChunk(Number(fd) === 2 ? 2 : 1, _decoder.decode(mem));
      }
      return BigInt(lenN);
    },
    exit(code) {
      _exited = true;
      throw new _ExitSignal(Number(code));
    },
    monotonic_nanos() {
      return BigInt(Math.round(performance.now() * 1e6));
    },
`)
	g.writef(`    %s(kind, delayMs) {
      _schedulePump(kind, delayMs);
    },
`, wasmweb.SchedulePumpImport)
}

// emitWebModuleImports writes the host side of modules/web/web.pr's
// `wasm_import`s (docs/web-apps.md#it-must-be-usable-without-bindgen). An
// event listener delivers each event to the program's subscription
// (_deliver), so the subscriber runs before the listener returns.
func (g *jsGlueGenerator) emitWebModuleImports() {
	g.write(`    web_add_event_listener(target, kind_ptr, kind_len, sub_id) {
      _refLoad(target).addEventListener(_readString(kind_ptr, kind_len), (event) => {
        _deliver(sub_id, event);
      });
    },
    console_log(handle, message_ptr, message_len) {
      _refLoad(handle).log(_readString(message_ptr, message_len));
    },
    document_get_body(handle) {
      return _refStore(_refLoad(handle).body);
    },
    "[resource-drop]event"(handle) {
      _refRelease(handle);
    },
    "[resource-drop]element"(handle) {
      _refRelease(handle);
    },
`)
}

func (g *jsGlueGenerator) emitImportObject(modules []*Module) {
	g.write("// --- Import Implementations ---\n")
	g.write("const importObject = {\n")

	for _, m := range modules {
		g.writef("  %s: {\n", m.ImportModule)

		if m.ImportModule == wasmweb.ImportModule {
			g.emitBasePromiseEnvImports()
		}

		if m.HasJsValue {
			g.emitJsValueImports()
		}

		// Resource drop functions. Import name must match the WIT/component-model
		// canonical naming ("[resource-drop]<kebab-case>") that codegen.go's
		// emitResource emits on the .pr side — see toKebab, which both generators
		// must share rather than deriving this name independently (T1506).
		for _, res := range m.Resources {
			if res.Drop {
				importName := "[resource-drop]" + toKebab(res.Name)
				g.writef("    \"%s\"(handle) {\n", importName)
				g.write("      _refRelease(handle);\n")
				g.write("    },\n")
			}

			for _, method := range res.Methods {
				g.emitMethodImport(res.Name, method)
			}

			if res.Parent != "" {
				g.emitConversionImport(res)
			}
		}

		// Free functions
		for _, f := range m.Functions {
			g.emitFreeFuncImport(f)
		}

		g.write("  },\n")
	}

	g.write("};\n\n")
}

func (g *jsGlueGenerator) emitMethodImport(resourceName string, f Func) {
	importName := f.ImportName
	if importName == "" {
		importName = resourceName + "." + f.Name
	}

	// Build JS parameter list
	jsParams := g.buildJSParams(f)

	g.writef("    \"%s\"(%s) {\n", importName, strings.Join(jsParams, ", "))

	owner := importOwner(importName)
	switch f.Kind {
	case FuncConstructor:
		g.emitConstructorBody(owner, f, jsParams)
	case FuncStatic:
		g.emitStaticBody(owner, importName, f)
	default:
		g.emitMethodBody(owner, importName, f)
	}

	g.write("    },\n")
}

// emitConversionImport implements the import of res's checked conversion
// (codegen.go's conversionFunc): whether the object a wrapper's handle holds is
// an instance of res's interface object, answered with a new handle to that
// object, which the converted wrapper owns, or with 0. The failure path stores
// nothing, so it has nothing to release. An interface the host does not define
// has no instances, so a missing interface object is a 0 — not the
// ReferenceError a bare `instanceof` would throw out of the import. A
// Resource's Name is its interface's IDL name (convertInterface), which is the
// global the interface object is reached by.
func (g *jsGlueGenerator) emitConversionImport(res Resource) {
	g.writef("    \"%s\"(%s) {\n", conversionImportName(res.Name), jsReceiverParam)
	g.writef("      const %s = _refLoad(%s);\n", jsResultLocal, jsReceiverParam)
	g.writef("      return typeof %[1]s === \"function\" && %[2]s instanceof %[1]s ? _refStore(%[2]s) : 0;\n", res.Name, jsResultLocal)
	g.write("    },\n")
}

func (g *jsGlueGenerator) emitFreeFuncImport(f Func) {
	importName := f.ImportName
	if importName == "" {
		importName = f.Name
	}
	jsParams := g.buildJSParams(f)

	g.writef("    \"%s\"(%s) {\n", importName, strings.Join(jsParams, ", "))
	// Free functions just call the global function
	g.writef("      return %s(%s);\n", idlCamelCase(f.Name), strings.Join(jsParams, ", "))
	g.write("    },\n")
}

// The names the glue gives its own parameters around a WebIDL operation's
// arguments — the receiver handle a method takes first, and the return pointer
// a string result comes back through, last — and the locals an import body
// declares beside them: the object a constructor creates, and a nullable
// interface result tested for null — or the object a conversion tests for its
// interface — before it is stored. Each begins with a `$`,
// and a name derived from a WebIDL argument never does: the WebIDL lexer's
// identifiers are letters, digits, `_` and `-` (isIdentStart, isIdentContinue),
// idlToSnake writes each `-` as `_` (or drops a leading one) and with
// sanitizeIdent adds only `_`, and the one `$` such a name can carry is the one
// jsParamName's escape puts at its end. So no argument can take one of these
// names, whatever it is called (#689, #690).
const (
	jsReceiverParam      = "$handle"
	jsReturnPointerParam = "$retptr"
	jsConstructedLocal   = "$obj"
	jsResultLocal        = "$result"
)

// jsStringParams returns the names of the (pointer, length) pair a string
// argument named name crosses as. Neither can be another argument's name: the
// one `$` such a name can carry is jsParamName's, at its end, and these two
// continue past theirs.
func jsStringParams(name string) (pointer, length string) {
	return name + "$ptr", name + "$len"
}

func (g *jsGlueGenerator) buildJSParams(f Func) []string {
	var params []string

	// Methods get a handle parameter first
	if f.Kind == FuncMethod {
		params = append(params, jsReceiverParam)
	}

	for _, p := range f.Params {
		name := jsParamName(p.Name)
		ref := p.Type
		// Unwrap option for the flat parameter
		if ref.Kind == OptionKind {
			ref = *ref.Elem
		}
		// String parameters are ptr+len pairs
		if isStringType(ref) {
			pointer, length := jsStringParams(name)
			params = append(params, pointer, length)
		} else {
			params = append(params, name)
		}
	}

	// A string or nullable built-in result comes back through a trailing return
	// pointer — last, the position codegen's declareExterns gives it (see
	// _writeStringResult and _writeOptionalResult).
	if _, nullable := nullableBuiltinResult(f); nullable || returnsString(f) {
		params = append(params, jsReturnPointerParam)
	}

	return params
}

// returnsString reports whether f's result is a string, which the extern
// declares as a bare string. A nullable one is a nullable built-in result
// (nullableBuiltinResult).
func returnsString(f Func) bool {
	return len(f.Results) > 0 && isStringType(f.Results[0])
}

// nullableBuiltinResult returns the built-in of f's result when it is a nullable
// built-in, which the extern declares as `T?` and the host returns through a
// presence flag and the value (promiseExternResultType, _writeOptionalResult).
func nullableBuiltinResult(f Func) (TypeRef, bool) {
	if len(f.Results) == 0 || !isOptionOfBuiltin(f.Results[0]) {
		return TypeRef{}, false
	}
	return *f.Results[0].Elem, true
}

func (g *jsGlueGenerator) emitConstructorBody(owner string, f Func, jsParams []string) {
	// Convert parameters, call new Constructor(...), store ref
	args := g.buildJSCallArgs(f)
	g.writef("      const %s = new %s(%s);\n", jsConstructedLocal, owner, strings.Join(args, ", "))
	g.writef("      return _refStore(%s);\n", jsConstructedLocal)
}

func (g *jsGlueGenerator) emitStaticBody(owner, importName string, f Func) {
	args := g.buildJSCallArgs(f)
	call := fmt.Sprintf("%s%s(%s)", owner, jsProperty(importMember(importName)), strings.Join(args, ", "))
	g.emitReturnConversion(f, call)
}

// emitMethodBody implements an instance member's import. It resolves the member
// on the object, through its own prototype chain — unless another property may
// answer under its name there (f.ViaPrototype): a redeclaration on an interface
// inheriting from the declaring one, or a named property of an interface
// carrying [LegacyOverrideBuiltIns]. Its result would then cross under this
// member's type, so such an import calls the declaring interface's own member,
// read from its interface prototype object with the object as receiver
// (docs/wasm-bindings.md, "WebIDL to Promise", interface inheritance).
func (g *jsGlueGenerator) emitMethodBody(owner, importName string, f Func) {
	args := g.buildJSCallArgs(f)
	member := importMember(importName)
	const obj = "_refLoad(" + jsReceiverParam + ")"

	// Check if this is an attribute getter/setter.
	// Attribute import names have 3 parts: "Type.attrName.get/set"
	// Operation import names have 2 parts: "Type.methodName", or 3 when the
	// operation is the k-th of an overload set: "Type.methodName.k"
	parts := strings.Split(importName, ".")
	if len(parts) == 3 && parts[2] == "get" {
		call := obj + jsProperty(member)
		if f.ViaPrototype {
			call = fmt.Sprintf("Reflect.get(%s.prototype, \"%s\", %s)", owner, member, obj)
		}
		g.emitReturnConversion(f, call)
		return
	}
	if len(parts) == 3 && parts[2] == "set" {
		value := strings.Join(args, ", ")
		if f.ViaPrototype {
			g.writef("      Reflect.set(%s.prototype, \"%s\", %s, %s);\n", owner, member, value, obj)
		} else {
			g.writef("      %s%s = %s;\n", obj, jsProperty(member), value)
		}
		return
	}

	// An anonymous getter, setter or deleter is imported under its keyword
	// (convertOperation), which no IDL operation can be named, and the host
	// exposes it only as property access keyed by its first argument
	// (docs/wasm-bindings.md, "Supported subset"). WebIdlToIR has already
	// rejected one that does not take exactly that key, and a setter its value.
	switch member {
	case "getter":
		g.emitReturnConversion(f, fmt.Sprintf("%s[%s]", obj, propertyKey(f, args)))
		return
	case "setter":
		g.writef("      %s[%s] = %s;\n", obj, propertyKey(f, args), args[1])
		return
	case "deleter":
		g.emitReturnConversion(f, fmt.Sprintf("delete %s[%s]", obj, propertyKey(f, args)))
		return
	}

	call := fmt.Sprintf("%s%s(%s)", obj, jsProperty(member), strings.Join(args, ", "))
	if f.ViaPrototype {
		call = fmt.Sprintf("Reflect.apply(%s.prototype%s, %s, [%s])", owner, jsProperty(member), obj, strings.Join(args, ", "))
	}
	g.emitReturnConversion(f, call)
}

// propertyKey returns the property key an anonymous special operation's first
// argument, args[0], names. An unsigned long index crosses the boundary as a
// signed i32, and a property key gets no WebIDL conversion back to unsigned —
// `obj[-1]` names an ordinary property, not index 4294967295 — so `>>> 0`
// restores it.
func propertyKey(f Func, args []string) string {
	if p := f.Params[0].Type; p.Kind == BuiltinKind && p.Builtin == "u32" {
		return args[0] + " >>> 0"
	}
	return args[0]
}

// importMember returns the JS member an import invokes: the second dotted
// component of its import name — "Element.setAttribute", "Element.innerHTML.get"
// and "Element.setAttribute.2" all name a member of Element. The WebIDL front end
// writes the IDL identifier there verbatim, so this is the one place the glue
// reads a member name. It is never re-derived from the snake_case Promise name,
// which an overload ordinal (set_attribute_2) or an acronym (getURL → get_url)
// does not survive. An anonymous special operation has no member: its second
// component is its keyword ("Form.getter"), which emitMethodBody turns into
// property access.
func importMember(importName string) string {
	parts := strings.Split(importName, ".")
	if len(parts) < 2 {
		return importName
	}
	return parts[1]
}

// importOwner returns the JS object an import reaches its member through: the
// first dotted component of its import name, the IDL name of the interface or
// namespace that declares the member — "Element" in "Element.setAttribute",
// "console" in "console.log". It is the one place the glue reads that name, so a
// type named apart from its IDL definition (a namespace's Console) still reaches
// the host object by the IDL name: its interface object for a constructor, a
// static or a prototype read, or the namespace object itself.
func importOwner(importName string) string {
	owner, _, _ := strings.Cut(importName, ".")
	return owner
}

// jsProperty returns the property access that reaches member, an IDL
// identifier, on the object expression it follows: `.member`, or
// `["member"]` for a name with a `-` (`margin-top`), the one character an IDL
// identifier may carry and a JS identifier may not. Dot access there would
// still parse, as a subtraction, and read the wrong thing.
func jsProperty(member string) string {
	if strings.Contains(member, "-") {
		return `["` + member + `"]`
	}
	return "." + member
}

func (g *jsGlueGenerator) buildJSCallArgs(f Func) []string {
	var args []string
	for _, p := range f.Params {
		name := jsParamName(p.Name)
		ref := p.Type
		if ref.Kind == OptionKind {
			ref = *ref.Elem
		}
		if isStringType(ref) {
			pointer, length := jsStringParams(name)
			args = append(args, fmt.Sprintf("_readString(%s, %s)", pointer, length))
		} else if g.kinds.isJsValue(ref) {
			// A JsValue argument may be a temporary slot its builder made
			// (emitJsValueRuntime), released once read.
			args = append(args, fmt.Sprintf("_refTake(%s)", name))
		} else if isRefType(ref) {
			args = append(args, fmt.Sprintf("_refLoad(%s)", name))
		} else {
			args = append(args, name)
		}
	}
	return args
}

func (g *jsGlueGenerator) emitReturnConversion(f Func, call string) {
	if len(f.Results) == 0 {
		g.writef("      %s;\n", call)
		return
	}
	if elem, nullable := nullableBuiltinResult(f); nullable {
		// Presence flag and value through the trailing retptr, nothing returned
		g.writef("      _writeOptionalResult(%s, %s, \"%s\");\n", jsReturnPointerParam, call, optionalResultSetter(elem))
		return
	}
	if returnsString(f) {
		// String return: (ptr, len) through the trailing retptr, nothing returned
		g.writef("      _writeStringResult(%s, %s);\n", jsReturnPointerParam, call)
		return
	}
	isNullable := f.Results[0].Kind == OptionKind
	ret := f.Results[0]
	// Unwrap option for the flat return type
	if ret.Kind == OptionKind && ret.Elem != nil {
		ret = *ret.Elem
	}
	if isRefType(ret) {
		if isNullable {
			g.writef("      const %s = %s;\n", jsResultLocal, call)
			g.writef("      if (%s == null) return 0;\n", jsResultLocal)
			g.writef("      return _refStore(%s);\n", jsResultLocal)
		} else {
			g.writef("      return _refStore(%s);\n", call)
		}
	} else {
		g.writef("      return %s;\n", call)
	}
}

func (g *jsGlueGenerator) emitInstantiation() {
	g.write(`// --- WASM Instantiation ---
export async function init(wasmPath) {
  const response = await fetch(wasmPath);
  const { instance } = await WebAssembly.instantiateStreaming(response, importObject);
  wasm = instance;

`)
	g.emitRunInitialize()
	g.write(`
  return wasm.exports;
}

export { _refStore, _refLoad, _refRelease };
`)
}

// emitRunInitialize writes the body both loaders' init() run once the
// instance is bound to wasm: call _initialize and classify how it ended.
func (g *jsGlueGenerator) emitRunInitialize() {
	g.writef(`  // Call WASM %[1]s if exported. A program with no live registration ends
  // it in pal_exit, which lowers to the exit import — the only way to abort a
  // synchronous WASM call from a JS import is to throw, so exit() always
  // throws to unwind the call stack. That's expected on success, not a crash,
  // so _enter swallows exactly that case; a non-zero code (a panic, or an
  // explicit exit()) must still propagate so the caller learns the run failed
  // instead of getting exports back silently (T1506). A reactor's %[1]s
  // returns normally, leaving the instance alive for later host entries.
  if (wasm.exports.%[1]s) {
    _enter(() => wasm.exports.%[1]s());
  }
  _flushRemainder();
`, wasmweb.ExportInitialize)
}

// isStringType checks if a TypeRef maps to a string in the binding IR.
func isStringType(ref TypeRef) bool {
	return ref.Kind == BuiltinKind && ref.Builtin == "string"
}

// isRefType checks if a TypeRef maps to a JS object reference (handle).
//
// This intentionally returns true for *every* NamedKind, including JsValue. On the
// JS side a JsValue genuinely IS a ref-table handle (a JS value is stored/loaded via
// _refStore/_refLoad, identical to a resource), so the existing read/write glue is
// correct for it here. The Promise (WASM) side is where JsValue diverges from a
// resource — it marshals to/from the JsValue *enum* rather than an `i32 _handle`
// field; that asymmetry is decided by the kind registry (namedKinds) in codegen.go.
// Do NOT exclude JsValue here, or the JS-side conversion will break.
func isRefType(ref TypeRef) bool {
	if ref.Kind == NamedKind {
		return true
	}
	return false
}

// jsParamName converts a snake_case parameter name to a JS-safe identifier.
func jsParamName(name string) string {
	// Avoid every word a JS binding identifier cannot be. The glue is a
	// "use strict" ES module, so that is the ECMAScript reserved words (`await`
	// among them, which a module reserves), the words reserved only in strict
	// mode, and `arguments` and `eval`, which strict mode forbids as binding
	// names. The words sanitizeIdent already prefixes as Promise keywords are
	// listed too: the glue's guarantee does not depend on Promise's grammar.
	//
	// The escape appends a `$`, which no name derived from a WebIDL identifier
	// carries, so an escaped word cannot meet another argument's name: `class`
	// and `class_` stay distinct, as `_` would not keep them (#689).
	switch name {
	case "await", "break", "case", "catch", "class", "const", "continue", "debugger", "default",
		"delete", "do", "else", "enum", "export", "extends", "false", "finally", "for", "function",
		"if", "import", "in", "instanceof", "new", "null", "return", "super", "switch", "this",
		"throw", "true", "try", "typeof", "var", "void", "while", "with", "yield",
		"implements", "interface", "let", "package", "private", "protected", "public", "static",
		"arguments", "eval":
		return name + "$"
	}
	return name
}

// idlCamelCase converts snake_case back to camelCase for JS method names.
// "get_element_by_id" → "getElementById"
func idlCamelCase(s string) string {
	parts := strings.Split(s, "_")
	if len(parts) <= 1 {
		return s
	}
	var b strings.Builder
	b.WriteString(parts[0])
	for _, part := range parts[1:] {
		if len(part) == 0 {
			continue
		}
		r, size := utf8.DecodeRuneInString(part)
		b.WriteRune(unicode.ToUpper(r))
		b.WriteString(part[size:])
	}
	return b.String()
}
